/**
 * Generates expansion card modules from curated lists.
 * Run: node packages/charades/scripts/generate-expansions.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, '../src/data/expansions');
mkdirSync(outDir, { recursive: true });

const POP_CULTURE_DIFFICULTIES = [4, 5, 5, 6, 6, 7, 4, 5, 6, 7, 5, 4];
const FAMILY_DIFFICULTIES = [3, 4, 4, 5, 5, 6, 4, 5, 6, 4];
const UNIVERSAL_DIFFICULTIES = [4, 5, 6, 4, 5, 6, 7, 5, 6, 4, 5, 6, 7, 5, 4];

function esc(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function pad(num) {
  return String(num).padStart(3, '0');
}

function formatValue(value) {
  if (Array.isArray(value)) {
    return `[${value.map((entry) => formatValue(entry)).join(', ')}]`;
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }
  return `'${esc(value)}'`;
}

function emitCard([id, text, type, difficulty, extra]) {
  const parts = [`'${id}'`, `'${esc(text)}'`, `'${type}'`, String(difficulty)];
  if (extra && Object.keys(extra).length > 0) {
    const fields = Object.entries(extra)
      .map(([key, value]) => `${key}: ${formatValue(value)}`)
      .join(', ');
    parts.push(`{ ${fields} }`);
  }
  return `  card(${parts.join(', ')}),`;
}

function writeExpansion(filename, exportName, cards) {
  const body = cards.map(emitCard).join('\n');
  const content = `import { card } from '../helpers.js';

/** Auto-generated — run \`node packages/charades/scripts/generate-expansions.mjs\` */
export const ${exportName} = [
${body}
];
`;
  writeFileSync(join(outDir, filename), content);
  console.log(`${filename}: ${cards.length} cards`);
  return cards.length;
}

function deriveImageSearch(text, context, suffix, includeImageSearch) {
  if (includeImageSearch === false) {
    return undefined;
  }
  return [context || text, suffix].filter(Boolean).join(' ');
}

function pickDifficulty(cycle, index, fallback = 5) {
  return cycle[index % cycle.length] ?? fallback;
}

function buildCards({
  prefix,
  start,
  type,
  items,
  difficultyCycle = POP_CULTURE_DIFFICULTIES,
  searchSuffix = '',
  includeImageSearch = true,
}) {
  return items.map((item, index) => {
    const normalized = typeof item === 'string' ? { text: item } : item;
    const difficulty = normalized.difficulty ?? pickDifficulty(difficultyCycle, index);
    const extra = {};
    if (normalized.packId) {
      extra.packId = normalized.packId;
    }
    if (normalized.context) {
      extra.context = normalized.context;
    }
    if (normalized.definition) {
      extra.definition = normalized.definition;
    }
    if (normalized.emoji) {
      extra.emoji = normalized.emoji;
    }
    const imageSearch =
      normalized.imageSearch ??
      deriveImageSearch(normalized.text, normalized.context, searchSuffix, includeImageSearch);
    if (imageSearch) {
      extra.imageSearch = imageSearch;
    }
    return [
      `${prefix}${pad(start + index)}`,
      normalized.text,
      normalized.type ?? type,
      difficulty,
      extra,
    ];
  });
}

